package sections

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"slices"
)

// WordPress writes the section as a block for the kit Blocks plugin, into
// dir/<name>/:
//
//	block.json    the block's registration: kit/<name>, its content and variant attributes
//	render.php    WordPress's render file: hands the attributes to kit_blocks_render()
//	<name>.php    the compiled template
//	style.css     the section's CSS, loaded only on pages with the block
//	schema.json   the schema, which the plugin sanitises and fills content with, and the editor builds its form from
//	patterns.json the demos, registered as block patterns
//
// The block keeps its content as one object attribute, shaped by the schema,
// so a schema change is a migration of one value rather than of many.
func (s *Section) WordPress(dir string) error {
	out := filepath.Join(dir, s.Name)
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	variants := make([]string, len(s.Schema.Variants))
	for i, v := range s.Schema.Variants {
		variants[i] = v.Name
	}
	block := map[string]any{
		"$schema":     "https://schemas.wp.org/trunk/block.json",
		"apiVersion":  3,
		"name":        "kit/" + s.Name,
		"title":       s.Schema.Title,
		"category":    "kit-sections",
		"description": s.Schema.Description,
		"version":     fmt.Sprintf("%d", s.Schema.Version),
		"textdomain":  "kit-blocks",
		"attributes": map[string]any{
			"content": map[string]any{"type": "object", "default": map[string]any{}},
			"variant": map[string]any{"type": "string", "enum": variants, "default": variants[0]},
			"align":   map[string]any{"type": "string", "default": "full"},
		},
		"supports": map[string]any{
			"html":            false,
			"align":           []string{"full"},
			"customClassName": false,
			"reusable":        false,
			"inserter":        s.Schema.Inserter,
		},
		"editorScript": "kit-blocks-editor",
		// kit.css (registered by the plugin as "kit") first, so the section's
		// rules come after kit's, as on the docs site.
		"style":  []string{"kit", "file:./style.css"},
		"render": "file:./render.php",
	}
	var patterns []map[string]any
	for _, d := range s.Demos {
		v := d.Variant
		if v == "" {
			v = variants[0]
		}
		// A pattern leaves bound fields empty, so a block made from it shows
		// the site's details (its phone, its name) rather than the demo's.
		content := map[string]any{}
		for k, val := range d.Content {
			if i := slices.IndexFunc(s.Schema.Fields, func(f *Field) bool { return f.Name == k }); i >= 0 && s.Schema.Fields[i].Bind != "" {
				continue
			}
			content[k] = val
		}
		patterns = append(patterns, map[string]any{"title": s.Schema.Title + ": " + d.Title, "variant": v, "content": content})
	}
	files := map[string][]byte{
		"render.php":    []byte("<?php\n// Generated by kit build-wp. WordPress includes this with $attributes in scope.\necho kit_blocks_render(" + phpString(s.Name) + ", $attributes);\n"),
		s.Name + ".php": []byte(s.Template.PHP("sections/" + s.Name + "/" + s.Name + ".blade.php")),
	}
	for name, v := range map[string]any{"block.json": block, "patterns.json": patterns} {
		b, err := json.MarshalIndent(v, "", "  ")
		if err != nil {
			return err
		}
		files[name] = append(b, '\n')
	}
	for to, from := range map[string]string{"style.css": s.Name + ".css", "schema.json": s.Name + ".schema.json"} {
		b, err := os.ReadFile(filepath.Join(s.Dir, from))
		if err != nil {
			return err
		}
		files[to] = b
	}
	for name, b := range files {
		if err := os.WriteFile(filepath.Join(out, name), b, 0o644); err != nil { //nolint:gosec // plugin source files
			return err
		}
	}
	return nil
}

// Fixture is a demo with the HTML kit renders for it: a plugin's tests render
// the same content their own way and compare.
type Fixture struct {
	Section string         `json:"section"`
	Title   string         `json:"title"`
	Variant string         `json:"variant"`
	Content map[string]any `json:"content"`
	HTML    string         `json:"html"`
}

// Fixtures renders every demo.
func (s *Section) Fixtures() ([]Fixture, error) {
	var out []Fixture
	for _, d := range s.Demos {
		v := d.Variant
		if v == "" {
			v = s.Schema.Variants[0].Name
		}
		html, err := s.Render(d.Content, v)
		if err != nil {
			return nil, err
		}
		out = append(out, Fixture{s.Name, d.Title, v, d.Content, html})
	}
	return out, nil
}
