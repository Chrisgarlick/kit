// CgCms writes the section for a cg-cms app into dir: its compiled template,
// schema and CSS in sections/<name>/, and the block's view in
// views/<name>.blade.php. It returns the PHP for the section's block
// definition, a Cg\Cms\Schema\Block, for kit-blocks.php. site is the site
// settings schema, which bound fields' help names.
//
// The fields are cg-cms's, mapped from the schema: rich text becomes a plain
// textarea (never cg-cms's richText, whose HTML would reach the page as it
// is; kit_rich turns the marks into tags itself), a list a repeater, an
// image a media field, enums, heading levels and icons selects. A section
// with more than one layout gets a variant select first. The stored data
// goes back through kit_content(), which casts each value to its schema type.
func (s *Section) CgCms(dir string, site *Schema) (string, error) {
	if slices.ContainsFunc(s.Schema.Fields, func(f *Field) bool { return f.Name == "variant" }) {
		return "", fmt.Errorf("a field called variant would clash with the block's layout select")
	}
	out := filepath.Join(dir, "sections", s.Name)
	if err := os.MkdirAll(out, 0o755); err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Join(dir, "views"), 0o755); err != nil {
		return "", err
	}
	files := map[string][]byte{
		filepath.Join(out, s.Name+".php"): []byte(s.Template.PHP("sections/" + s.Name + "/" + s.Name + ".blade.php")),
		filepath.Join(dir, "views", s.Name+".blade.php"): []byte("{{-- Generated by kit build-cgcms: the kit-" + s.Name + " block. Don't edit. --}}\n" +
			"@once('kit-blocks:" + s.Name + "')\n@push('kit-styles')\n<link rel=\"stylesheet\" href=\"{{ kit_cgcms_asset('sections/" + s.Name + "/style.css') }}\">\n@endpush\n@endonce\n" +
			"{{ kit_cgcms_block('" + s.Name + "', $data) }}"), // no newline after: Blade would print it
	}
	for to, from := range map[string]string{"style.css": s.Name + ".css", "schema.json": s.Name + ".schema.json"} {
		b, err := os.ReadFile(filepath.Join(s.Dir, from))
		if err != nil {
			return "", err
		}
		files[filepath.Join(out, to)] = b
	}
	for name, b := range files {
		if err := os.WriteFile(name, b, 0o644); err != nil { //nolint:gosec // app source files
			return "", err
		}
	}
	return s.CgCmsBlock(site), nil
}

// CgCmsBlock is the PHP for the section's cg-cms block definition.
func (s *Section) CgCmsBlock(site *Schema) string {
	var b strings.Builder
	fmt.Fprintf(&b, "    Block::make(%s, %s)->fields([\n", phpString("kit-"+s.Name), phpString(s.Schema.Title))
	if len(s.Schema.Variants) > 1 {
		names := make([]string, len(s.Schema.Variants))
		var help []string
		for i, v := range s.Schema.Variants {
			names[i] = v.Name
			help = append(help, v.Name+": "+v.Label)
		}
		fmt.Fprintf(&b, "        Field::select('variant')->label('Layout')->options(%s)->default(%s)->help(%s),\n",
			phpList(names), phpString(names[0]), phpString(strings.Join(help, ". ")+"."))
	}
	for _, f := range s.CgCmsFields() {
		writeCgCmsField(&b, f, site, "        ")
	}
	fmt.Fprintf(&b, "    ])->view(%s),\n", phpString("kit-blocks::"+s.Name))
	return b.String()
}

// cgcmsWorkedOut lists the fields cg-cms's runtime works out for itself,
// which its blocks leave out of the admin: the header link that is the page
// being shown (kit_cgcms_block marks it from the request, as kit Blocks does
// in WordPress). A value stored before is still honoured.
var cgcmsWorkedOut = map[string][]string{"header": {"links.current"}}

// CgCmsFields is the section's fields as its cg-cms block has them: the
// schema's, less those cg-cms works out (cgcmsWorkedOut).
func (s *Section) CgCmsFields() []*Field {
	return withoutFields(s.Schema.Fields, cgcmsWorkedOut[s.Name], "")
}

func withoutFields(fields []*Field, drop []string, prefix string) []*Field {
	if len(drop) == 0 {
		return fields
	}
	var out []*Field
	for _, f := range fields {
		path := prefix + f.Name
		if slices.Contains(drop, path) {
			continue
		}
		if f.Type == "list" {
			c := *f
			c.Item = withoutFields(f.Item, drop, path+".")
			f = &c
		}
		out = append(out, f)
	}
	return out
}

// The cg-cms field type for each kit field type, which is also the name of
// its Field factory.
var cgcmsTypes = map[string]string{
	"text": "text", "textarea": "textarea", "rich-text": "textarea", "number": "number", "boolean": "boolean",
	"enum": "select", "url": "url", "image": "media", "heading-level": "select", "icon": "select", "list": "repeater",
}

func writeCgCmsField(b *strings.Builder, f *Field, site *Schema, indent string) {
	fmt.Fprintf(b, "%sField::%s(%s)", indent, cgcmsTypes[f.Type], phpString(f.Name))
	if f.Label != "" {
		fmt.Fprintf(b, "->label(%s)", phpString(f.Label))
	}
	// A bound field left empty shows the site's value, so it's never required.
	if f.Required && f.Bind == "" {
		b.WriteString("->required()")
	}
	switch f.Type {
	case "text", "textarea", "rich-text", "url":
		if f.Max > 0 {
			fmt.Fprintf(b, "->maxLength(%d)", f.Max)
		}
	case "enum":
		fmt.Fprintf(b, "->options(%s)", phpList(f.Options))
	case "heading-level":
		fmt.Fprintf(b, "->options(['1', '2', '3', '4'])")
	case "icon":
		fmt.Fprintf(b, "->options(%s)", phpList(append([]string{""}, IconNames...)))
	case "number":
		// cg-cms validates a number field's range (min: and max:).
		if f.Min != 0 || f.Max > 0 {
			fmt.Fprintf(b, "->min(%d)", f.Min)
		}
		if f.Max > 0 {
			fmt.Fprintf(b, "->max(%d)", f.Max)
		}
	case "image":
		if f.Alt == "required" {
			b.WriteString("->requireAlt()")
		}
		if f.Sizes != "" {
			fmt.Fprintf(b, "->preset(%s)", phpString(f.Sizes))
		}
	case "list":
		if f.Min > 0 {
			fmt.Fprintf(b, "->min(%d)", f.Min)
		}
		if f.Max > 0 {
			fmt.Fprintf(b, "->max(%d)", f.Max)
		}
		if i := slices.IndexFunc(f.Item, func(it *Field) bool { return it.Type == "text" }); i >= 0 {
			fmt.Fprintf(b, "->rowLabel(%s)", phpString(f.Item[i].Name))
		}
	}
	if d, ok := cgcmsDefault(f); ok {
		fmt.Fprintf(b, "->default(%s)", d)
	}
	if h := cgcmsHelp(f, site); h != "" {
		fmt.Fprintf(b, "->help(%s)", phpString(h))
	}
	if f.Type == "list" {
		b.WriteString("->fields([\n")
		for _, it := range f.Item {
			writeCgCmsField(b, it, site, indent+"    ")
		}
		b.WriteString(indent + "])")
	}
	b.WriteString(",\n")
}

// cgcmsDefault is a field's default as a PHP literal, typed as cg-cms's
// Field::default takes it: a number a number, a toggle true, text and selects
// strings (a select's options are strings). An enum or heading level always
// has one (as kit fills them); a list's isn't carried, nor a toggle's false
// (a toggle starts off).
func cgcmsDefault(f *Field) (string, bool) {
	switch d := f.Default.(type) {
	case string:
		return phpString(d), true
	case float64:
		n := strconv.FormatFloat(d, 'f', -1, 64)
		if f.Type == "number" {
			return n, true
		}
		return phpString(n), true
	case bool:
		if d {
			return "true", true
		}
		return "", false
	case nil:
		switch f.Type {
		case "enum":
			return phpString(f.Options[0]), true
		case "heading-level":
			return phpString("2"), true
		}
	}
	return "", false
}

func cgcmsHelp(f *Field, site *Schema) string {
	help := f.Help
	add := func(s string) {
		if help != "" {
			help += " "
		}
		help += s
	}
	if f.Type == "rich-text" && !strings.Contains(help, "*") {
		add("*Stars* for italics, **double stars** for bold.")
	}
	if f.Type == "number" && f.Max > 0 && !strings.Contains(help, strconv.Itoa(f.Max)) {
		add(fmt.Sprintf("From %d to %d.", f.Min, f.Max))
	}
	if name, ok := strings.CutPrefix(f.Bind, "site."); ok {
		what := "the site's details"
		if site != nil {
			if i := slices.IndexFunc(site.Fields, func(sf *Field) bool { return sf.Name == name }); i >= 0 && site.Fields[i].Label != "" {
				what = "the site's " + strings.ToLower(site.Fields[i].Label[:1]) + site.Fields[i].Label[1:]
			}
		}
		add("Left empty, it shows " + what + ".")
	}
	return help
}

func phpList(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = phpString(s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// CgCmsBlocksFile is kit-blocks.php: every section's block definition.
func CgCmsBlocksFile(blocks []string) string {
	return `<?php
// Generated by kit build-cgcms: kit's sections as cg-cms blocks. Don't edit;
// run kit build-cgcms again. Add them with
//     return [...require __DIR__.'/kit-blocks.php', /* the app's own */];
// Each renders through views/<name>.blade.php and kit/cgcms.php.

declare(strict_types=1);

use Cg\Cms\Schema\Block;
use Cg\Cms\Schema\Field;

require_once __DIR__ . '/kit/cgcms.php';

return [
` + strings.Join(blocks, "") + "];\n"
}

// CgCmsFixture is a demo as a cg-cms block stores it (its fields and the
// variant, selects as strings) with the HTML kit renders for it.
type CgCmsFixture struct {
	Section string         `json:"section"`
	Title   string         `json:"title"`
	Data    map[string]any `json:"data"`
	HTML    string         `json:"html"`
}

// CgCmsFixtures renders every demo, its content as cg-cms would store it.
func (s *Section) CgCmsFixtures() ([]CgCmsFixture, error) {
	fx, err := s.Fixtures()
	if err != nil {
		return nil, err
	}
	out := make([]CgCmsFixture, len(fx))
	for i, f := range fx {
		data := cgcmsData(s.Schema.Fields, f.Content)
		if len(s.Schema.Variants) > 1 {
			data["variant"] = f.Variant
		}
		out[i] = CgCmsFixture{f.Section, f.Title, data, f.HTML}
	}
	return out, nil
}

// cgcmsData is content as cg-cms's admin stores it: a heading level is a
// select, so a string.
func cgcmsData(fields []*Field, content map[string]any) map[string]any {
	out := map[string]any{}
	for k, v := range content {
		i := slices.IndexFunc(fields, func(f *Field) bool { return f.Name == k })
		if i < 0 {
			out[k] = v
			continue
		}
		switch f := fields[i]; {
		case f.Type == "heading-level":
			if n, ok := v.(float64); ok {
				v = strconv.FormatFloat(n, 'f', -1, 64)
			}
		case f.Type == "list":
			if list, ok := v.([]any); ok {
				items := make([]any, len(list))
				for j, it := range list {
					if m, ok := it.(map[string]any); ok {
						items[j] = cgcmsData(f.Item, m)
					} else {
						items[j] = it
					}
				}
				v = items
			}
		}
		out[k] = v
	}
	return out
}
