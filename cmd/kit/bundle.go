package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/evanw/esbuild/pkg/api"
)

// bundleCharts builds the chart renderer as one plain script for QuickJS
// (crates/kit-render): no modules, no DOM, ES2020.
func bundleCharts(args []string) error {
	fl := flag.NewFlagSet("bundle-charts", flag.ExitOnError)
	root := fl.String("root", ".", "the kit repository")
	_ = fl.Parse(args)
	entry := filepath.Join(*root, "crates", "kit-render", "js", "entry.js")
	out := filepath.Join(*root, "crates", "kit-render", "js", "kit-charts.js")
	r := api.Build(api.BuildOptions{
		EntryPoints:       []string{entry},
		Bundle:            true,
		Format:            api.FormatIIFE,
		Target:            api.ES2020,
		MinifyWhitespace:  true,
		MinifySyntax:      true,
		MinifyIdentifiers: true,
		LegalComments:     api.LegalCommentsNone,
		Write:             false,
	})
	if len(r.Errors) > 0 {
		var msgs []string
		for _, e := range r.Errors {
			msgs = append(msgs, e.Text)
		}
		return errors.New(strings.Join(msgs, "; "))
	}
	body := append([]byte("// Generated by `kit bundle-charts` from core/charts-static.js. Don't edit.\n"), r.OutputFiles[0].Contents...)
	if err := os.WriteFile(out, body, 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s (%.1f KB)\n", out, float64(len(body))/1024)
	return nil
}
